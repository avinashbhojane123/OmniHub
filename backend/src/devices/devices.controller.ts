import {
  Controller,
  Post,
  Get,
  Body,
  Query,
  UseGuards,
  HttpCode,
  HttpStatus,
  BadRequestException,
} from '@nestjs/common';
import { DevicesService, SyncResult } from './devices.service';
import {
  RegisterDeviceDto,
  BindDeviceDto,
  KeystoreChallengeDto,
  VerifyKeystoreDto,
  UpdateFcmTokenDto,
  OfflineSyncDto,
} from './dto/device.dto';
import { RateLimitGuard } from '../common/guards/rate-limit.guard';

@UseGuards(RateLimitGuard)
@Controller('devices')
export class DevicesController {
  constructor(private readonly devicesService: DevicesService) {}

  /**
   * Register or update an Android device with FCM token & hardware specs.
   */
  @Post('register')
  @HttpCode(HttpStatus.OK)
  async register(@Body() dto: RegisterDeviceDto) {
    if (!dto || !dto.deviceId) {
      throw new BadRequestException('deviceId is required');
    }
    const device = await this.devicesService.registerDevice(dto);
    return {
      success: true,
      deviceId: device.deviceId,
      nickname: device.nickname,
      isBound: device.isBound,
    };
  }

  /**
   * Bind an Android device to a user session.
   */
  @Post('bind')
  @HttpCode(HttpStatus.OK)
  async bind(@Body() dto: BindDeviceDto) {
    if (!dto || !dto.deviceId || !dto.nickname) {
      throw new BadRequestException('deviceId and nickname are required');
    }
    const device = await this.devicesService.bindDevice(dto);
    return {
      success: true,
      deviceId: device.deviceId,
      nickname: device.nickname,
      isBound: device.isBound,
    };
  }

  /**
   * Issue a cryptographic nonce challenge for Android Keystore hardware verification.
   */
  @Post('keystore/challenge')
  @HttpCode(HttpStatus.OK)
  async requestChallenge(@Body() dto: KeystoreChallengeDto) {
    if (!dto || !dto.deviceId) {
      throw new BadRequestException('deviceId is required');
    }
    return await this.devicesService.generateKeystoreChallenge(dto.deviceId);
  }

  /**
   * Verify digital signature generated by Android Keystore hardware key.
   */
  @Post('keystore/verify')
  @HttpCode(HttpStatus.OK)
  async verifySignature(@Body() dto: VerifyKeystoreDto) {
    if (!dto || !dto.deviceId || !dto.signature || !dto.challenge) {
      throw new BadRequestException(
        'deviceId, signature, and challenge are required',
      );
    }
    return await this.devicesService.verifyKeystoreSignature(dto);
  }

  /**
   * Rotate or update FCM push notification token.
   */
  @Post('token')
  @HttpCode(HttpStatus.OK)
  async updateToken(@Body() dto: UpdateFcmTokenDto) {
    if (!dto || !dto.deviceId || !dto.fcmToken) {
      throw new BadRequestException('deviceId and fcmToken are required');
    }
    await this.devicesService.updateFcmToken(dto);
    return { success: true };
  }

  /**
   * Offline synchronization endpoint for Android offline-first data queues.
   */
  @Post('sync')
  @HttpCode(HttpStatus.OK)
  async sync(@Body() dto: OfflineSyncDto): Promise<SyncResult> {
    if (!dto || !dto.deviceId) {
      throw new BadRequestException('deviceId is required');
    }
    return await this.devicesService.syncOfflineData(dto);
  }

  /**
   * Telemetry status check for Android device management.
   */
  @Get('status')
  async getStatus() {
    return await this.devicesService.getStatus();
  }
}

